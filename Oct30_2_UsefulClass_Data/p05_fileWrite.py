# ㅋㅋㅋㅋ -encoding-> 10101 -decoding-> ㅋ
# ㅋ         A방식   ->  00011     A      ㅋ
# ㅋ         B방식   ->  11010     C      깨짐
#            C방식   ->  00001

# encoding -> 저장함
# decoding -> 사람한태 보여줌
#######################################################
# 데이터 -> 임시저장 : 변수형태로 RAM에 저장
#        -> 영구저장 : 파일형태로 SSD/HDD에 저장
#######################################################

msg = input("뭐뭐 : ")
print("-----------")
print(msg)
# 파일 열기 (파일은 만들어주는데, 폴더는 안만들어줌)
# 경로쓸때 \이거 \\두개 써야함 왜냐면 "\t" "\n" "\k" 이런게 있어서
# 근데 \이거 말고 / 이거 써도 파이썬이 봐줌
# open() ()안에 열고싶은 경로 입력   
f = open("C:\\Users/soldesk/Desktop/1030/p05.txt", "a", encoding="utf-8") #utf-8방식이 제일 많이씀
                                # r : read 
                                # w : write -> 쓸때마다 지우고 새로씀
                                # a : append -> 쓸때마다 뒤에다 붙여줌
f.write(msg + "\n")  
f.close()