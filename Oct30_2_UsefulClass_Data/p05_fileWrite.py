# 확장자 - Windows에만 존재하는 허상
#        -> 사람들이 보고 아 그 파일인가 보다 짐작하게 해주는 것
#   .txt : 메모장에서 열면 제일 보기 좋게 열리는 파일
#   .xlsx : 엑셀에서 열면 제일 보기 좋게 열리는 파일
